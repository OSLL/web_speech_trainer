class QuestionTemplate(str):
    """Строка-шаблон вопроса со сложностью"""

    difficulty: str

    def __new__(cls, text: str, difficulty: str = MEDIUM):
        obj = super().__new__(cls, text)
        obj.difficulty = difficulty
        return obj


